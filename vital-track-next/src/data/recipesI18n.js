/**
 * Traduction clinique individualisée des 76 recettes
 */
export function getLocalizedRecipe(recipe, lang = 'fr') {
  if (!recipe) return recipe;
  const currentLang = (lang && ['fr', 'fr-CA', 'en', 'es'].includes(lang)) ? lang : 'fr';
  if (currentLang === 'fr' || currentLang === 'fr-CA') return recipe;

  const localizedTitle = translateRecipeText(recipe.title, currentLang);
  const localizedSubtitle = translateRecipeText(recipe.subtitle, currentLang);
  const localizedCategoryLabel = (CATEGORY_I18N[recipe.category] && CATEGORY_I18N[recipe.category][currentLang])
    || translateRecipeText(recipe.categoryLabel, currentLang);
  const localizedPrepTime = translateRecipeText(recipe.prepTime, currentLang);
  const localizedCookTime = translateRecipeText(recipe.cookTime, currentLang);
  const localizedDifficulty = (DIFFICULTY_I18N[recipe.difficulty] && DIFFICULTY_I18N[recipe.difficulty][currentLang])
    || recipe.difficulty;

  const localizedTags = (recipe.tags || []).map(t => (TAGS_I18N[t] && TAGS_I18N[t][currentLang]) || translateRecipeText(t, currentLang));
  const localizedTargetEmunctories = (recipe.targetEmunctories || []).map(e => (EMUNCTORY_I18N[e] && EMUNCTORY_I18N[e][currentLang]) || translateRecipeText(e, currentLang));

  const localizedDescription = translateRecipeText(recipe.description, currentLang);
  const localizedVitalistAction = translateRecipeText(recipe.vitalistAction, currentLang);

  const localizedIngredients = (recipe.ingredients || []).map(ing => ({
    ...ing,
    name: translateRecipeText(ing.name, currentLang),
    unit: translateRecipeText(ing.unit, currentLang),
    note: translateRecipeText(ing.note, currentLang)
  }));

  const localizedInstructions = (recipe.instructions || []).map(step => translateRecipeText(step, currentLang));
  const localizedNutritionalHighlights = (recipe.nutritionalHighlights || []).map(h => translateRecipeText(h, currentLang));

  return {
    ...recipe,
    title: localizedTitle,
    subtitle: localizedSubtitle,
    categoryLabel: localizedCategoryLabel,
    prepTime: localizedPrepTime,
    cookTime: localizedCookTime,
    difficulty: localizedDifficulty,
    tags: localizedTags,
    targetEmunctories: localizedTargetEmunctories,
    description: localizedDescription,
    vitalistAction: localizedVitalistAction,
    ingredients: localizedIngredients,
    instructions: localizedInstructions,
    nutritionalHighlights: localizedNutritionalHighlights
  };
}

